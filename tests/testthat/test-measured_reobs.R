f_reobs <- function() fixture_path("reobs/reobs_test.zip")

test_that("read_reobs reads the zip: time bounds, fill values, counts, attributes", {
  r <- read_reobs(f_reobs())
  expect_equal(nrow(r), 6)
  expect_equal(r$timestamp_start_utc[1], as.POSIXct("2022-06-01 00:00", tz = "UTC"))
  expect_equal(as.numeric(r$timestamp_end_utc - r$timestamp_start_utc, units = "mins"), rep(60, 6))
  expect_equal(attr(r$timestamp_start_utc, "tzone"), "UTC")
  expect_equal(r$mlh_chm15k, c(500, 600, NA, 700, NA, 800))
  expect_false(any(is.nan(r$mlh_chm15k)))
  expect_equal(r$mlh_chm15k_nb, c(60L, 40L, 20L, 29L, NA, 45L))
  expect_equal(r$mlh_cl31_nb, c(4L, 2L, NA, 1L, 3L, NA))
  expect_equal(r$mlh_cl31_std, c(10, 15, NA, NA, 5, NA))
  m <- attr(r, "reobs_meta")
  expect_equal(m$product_version, "2026.08.1")
  expect_equal(m$uuid, "00000000-test-reobs")
  expect_equal(m$licence, "Inspired by CC-BY")
  expect_equal(m$station_alt, 156)
  # nothing left behind next to the zip
  expect_equal(list.files(dirname(f_reobs())), "reobs_test.zip")
})

test_that("read_reobs aborts on missing variables and on bad time bounds", {
  expect_error(read_reobs(f_reobs(), vars = "mlh_nothing"), "not found")
  tmp <- tempfile(fileext = ".nc")
  tmin <- 27000000 + 60 * (0:2)
  dt <- ncdf4::ncdim_def("time", "minutes since 1970-01-01", tmin)
  db <- ncdf4::ncdim_def("nbnds", "", 1:2, create_dimvar = FALSE)
  vb <- ncdf4::ncvar_def("time_bnds", "", list(db, dt), prec = "integer")
  vm <- ncdf4::ncvar_def("mlh_cl31", "m", list(dt), missval = NaN, prec = "float")
  nc <- ncdf4::nc_create(tmp, list(vb, vm), force_v4 = TRUE)
  ncdf4::ncvar_put(nc, vb, as.integer(rbind(tmin, tmin + 30))) # 30-min bounds: not hourly
  ncdf4::ncvar_put(nc, vm, c(1, 2, 3))
  ncdf4::nc_close(nc)
  expect_error(read_reobs(tmp, vars = "mlh_cl31"), "time_bnds")
})

