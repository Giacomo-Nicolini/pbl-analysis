test_that("standardize_reobs_mlh writes valid standard tables for both instruments", {
  r <- read_reobs(f_reobs())
  ex <- read_exclusions(fixture_path("exclusion_periods.csv"))
  ch <- standardize_reobs_mlh(r, "chm15k", "XX-Tst", ex, 1)
  expect_equal(ch$data$source_id[1], "sirta_mlh_chm15k")
  expect_equal(ch$data$qc_flag, c(0L, 1L, NA, NA, NA, 0L))
  expect_equal(ch$data$pblh_m, c(500, 600, NA, NA, NA, 800))
  expect_equal(ch$data$uncertainty_m, c(20, 30, NA, NA, NA, 50))
  expect_equal(ch$data$n_samples, c(60L, 40L, 20L, 29L, NA, 45L))
  expect_true(all(c("x_cbh_m", "x_tcf_oktas", "x_ablh_m", "x_coverage") %in% names(ch$data)))
  expect_equal(ch$meta$method_class, "aerosol")
  expect_equal(ch$meta$time_reference, "interval_mean")
  expect_equal(ch$meta$height_reference, "agl")
  expect_match(ch$meta$citation, "Kotthaus2020")
  expect_match(ch$meta$processing_history, "2026.08.1")
  expect_true(validate_standard_pblh(ch$data, ch$meta))

  cl <- standardize_reobs_mlh(r, "cl31", "XX-Tst", ex, 1)
  # rows from the first to the last hour with data: hour 6 has neither value nor count
  expect_equal(nrow(cl$data), 5)
  expect_equal(cl$data$qc_flag, c(0L, 1L, NA, NA, 0L))
  expect_equal(cl$data$pblh_m, c(450, 550, NA, NA, 300))
  expect_false("x_ablh_m" %in% names(cl$data))
  expect_match(cl$meta$retrieval_algorithm, "CABAM")
  dir <- tempfile("std_")
  p <- write_standard_pblh(cl$data, cl$meta, dir)
  back <- read_standard_pblh(p[["data"]])
  expect_equal(back$pblh_m, cl$data$pblh_m)
  expect_error(standardize_reobs_mlh(r, "ct25k", "XX-Tst", ex, 1), "Unknown")
})
